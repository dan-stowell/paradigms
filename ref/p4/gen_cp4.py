#!/usr/bin/env python3
"""Generate hot-template emitters. No third-party dependencies; output is build-only.
Usage: python3 ref/p4/gen_cp4.py DATA [build/cp4_generated.h]
Rank by descending node count, then ascending template ID (deterministic ties).
Each template function dispatches its segment to a straight-line copy/patch arm.
"""
import array
import collections
import pathlib
import sys

D = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else 'build/cp4_generated.h')
def rd(name, typ):
    a = array.array(typ)
    a.frombytes((D / name).read_bytes())
    if sys.byteorder != 'little':
        a.byteswap()
    return a
nt = rd('node_tmpl.u32', 'I')
to = rd('tmpl.off.u64', 'Q')
tb = (D / 'tmpl.bin').read_bytes()
so = rd('tmpl_seg_off.u32', 'I')
se = rd('tseg_end.u32', 'I')
ho = rd('tmpl_hole_off.u32', 'I')
ha = rd('hole_at.u32', 'I')
hw = rd('hole_w.u8', 'B')
he = rd('hole_enc.u8', 'B')
hr = rd('hole_rtype.u16', 'H')
counts = collections.Counter(nt)
hot = sorted(counts, key=lambda t: (-counts[t], t))[:4096]
lines = ['/* Generated by ref/p4/gen_cp4.py; do not edit. */',
         'typedef void (*EmitFn)(u8 *, u64, u32, const i64 *, const i64 *, const u64 *, RelVec *);']
for t in hot:
    lines.append(f'static void emit_{t}(u8 *P, u64 dest, u32 seg, const i64 *v, const i64 *a, const u64 *at, RelVec *rel) {{')
    nseg = so[t+1] - so[t]
    if nseg > 1:
        lines.append('switch (seg) {')
    lo = 0
    for s, hi in enumerate(se[so[t]:so[t+1]]):
        if nseg > 1:
            lines.append(f'case {s}:')
        raw = tb[to[t]+lo:to[t]+hi]
        if raw:
            literal = ''.join('\\x%02x' % b for b in raw)
            lines.append(f'memcpy(P, "{literal}", {len(raw)});')
        for h in range(ho[t], ho[t+1]):
            if not lo <= ha[h] < hi:
                continue
            assert ha[h] + hw[h] <= hi
            j, p, width = h-ho[t], ha[h]-lo, hw[h]
            if he[h] == 1:
                typ = {1:'u8', 2:'u16', 4:'u32', 8:'u64'}[width]
                lines.append(f'{{ {typ} x = ({typ})v[{j}]; memcpy(P + {p}, &x, {width}); }}')
            elif he[h] == 2:
                assert width == 4
                lines.append(f'{{ i32 x = (i32)((i64)(at[v[{j}]] + a[{j}]) - (i64)(dest + {p+4})); memcpy(P + {p}, &x, 4); }}')
            elif he[h] == 3:
                lines.append(f'push(rel, (Rel){{dest + {p}, a[{j}], (u32)v[{j}], {hr[h]}, {width}}});')
            else:
                raise ValueError('unknown encoding')
        lines.append('return;')
        lo = hi
    if nseg > 1:
        lines.append('default: abort();\n}')
    lines.append('}')
lines.append(f'static EmitFn const cp4_table[{len(to)-1}] = {{')
lines.extend(f'[{t}] = emit_{t},' for t in hot)
lines.append('};')
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text('\n'.join(lines) + '\n')
kind = rd('item_kind.u8', 'B')
refs = rd('item_ref.u32', 'I')
segs = rd('item_seg.u32', 'I')
go = rd('glue.off.u64', 'Q')
hotset = set(hot)
mechanism = collections.Counter()
for k,r,s in zip(kind, refs, segs):
    if k == 0:
        path, size = 'glue', go[r+1]-go[r]
    else:
        t = nt[r]
        path = 'fast' if t in hotset else 'slow'
        b = so[t]
        size = se[b+s] - (se[b+s-1] if s else 0)
    mechanism[path+'_items'] += 1
    mechanism[path+'_bytes'] += size
print('templates', len(to)-1, 'hot', len(hot), 'hot_nodes', sum(counts[t] for t in hot), 'nodes', len(nt))
print('generated_C_bytes', out.stat().st_size)
for k,v in sorted(mechanism.items()):
    print(k, v)
