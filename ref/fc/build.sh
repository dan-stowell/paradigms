#!/usr/bin/env bash
# Build ref/fc's copy of fc (simd-lang's compiler, driver/fc at simd-lang a99d791) with the problem-4 dump
# (ref/fc/src/p4dump.go) into build/fcp4, in a GOROOT of our own (data/goroot-p4). It replays what
# simd-lang's driver/mkcompiler.sh and driver/mkfc.sh do to a copy of the stock GOROOT, but writes nothing
# into simd-lang (its patch scripts are only run, with our GOROOT as their argument), and skips the two
# stock tools mkcompiler.sh also builds (compile-sb, link-sb), which fc does not run.
#   ref/fc/build.sh            -> build/fcp4
set -e
here=$(cd "$(dirname "$0")/../.." && pwd)
T=/home/exedev/targets/simd-lang
D=$T/driver
src=$(GOTOOLCHAIN=local go env GOROOT)
dst=${P4_GOROOT:-/home/exedev/paradigms/data/goroot-p4}
if [ ! -d "$dst" ]; then
  cp -a "$src" "$dst.tmp"
  # mkcompiler.sh's additions to the GOROOT (the files it copies from $src onto the copy are no-ops here)
  cp $D/baseline/sbbaseline.go "$dst.tmp/src/cmd/compile/internal/ssagen/"
  cp $D/baseline/sbshard.go "$dst.tmp/src/cmd/compile/internal/noder/"
  cp $D/x86/sbspan.go "$dst.tmp/src/cmd/internal/obj/x86/"
  cp $D/runtime/sbfork.go "$dst.tmp/src/runtime/"
  cp $D/zygote/sbzygote.go "$dst.tmp/src/cmd/compile/"
  sed -i 's|^\tgc.Main(archInit)|\tsbZygote()\n\tgc.Main(archInit)|' "$dst.tmp/src/cmd/compile/main.go"
  python3 $D/early_export.py "$dst.tmp/src/cmd/compile/internal/gc" "$dst.tmp/src/cmd/internal/obj"
  # mkfc.sh's patches
  python3 $D/gotypes/patch.py "$src/src/go/types" "$dst.tmp/src/go/types"
  python3 $D/rtbump/patch.py "$dst.tmp/src/runtime"
  python3 $D/objpatch.py "$dst.tmp/src/cmd/internal/obj"
  mkdir -p "$dst.tmp/src/cmd/internal/fclinklib"
  cp $D/fclink/*.go "$dst.tmp/src/cmd/internal/fclinklib/"
  SB_GOROOT="$dst.tmp" bash $D/mkfcasmlib.sh
  mv "$dst.tmp" "$dst"
fi
d="$dst/src/cmd/fcp4"
mkdir -p "$d" "$here/build"
find "$d" -maxdepth 1 -name '*.go' -delete
cp "$here"/ref/fc/src/*.go "$d/"
# what the stock compiler inlines in the runtime's packages (mkfc.sh's zz_inltab.go)
tab=$here/build/inltab-$(GOTOOLCHAIN=local go env GOVERSION).txt
if [ ! -s "$tab" ]; then
  gc=$(mktemp -d); m=$(mktemp)
  (cd "$src/src" && CGO_ENABLED=0 GOTOOLCHAIN=local GOFLAGS= GOCACHE="$gc" go build -gcflags=all=-m runtime) 2> "$m"
  python3 $D/mkinltab.py "$m" > "$tab"; rm -rf "$gc" "$m"
fi
{ echo 'package main'; echo; echo '// Generated by ref/fc/build.sh from '"$(basename "$tab")"'.'; echo 'func init() {'; echo '	stockInl = map[string]struct{}{'
  sed 's/\t/\\t/; s/.*/\t\t"&": {},/' "$tab"; echo '	}'; echo '}'; } > "$d/zz_inltab.go"
(cd "$dst/src" && GOROOT="$dst" GOTOOLCHAIN=local GOFLAGS= "$dst/bin/go" build -o "$here/build/fcp4" cmd/fcp4)
echo "built $here/build/fcp4"
