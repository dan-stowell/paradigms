#!/usr/bin/env bash
# Regenerate in scratch, verify all old files, then publish only raw aux columns.
set -euo pipefail
here=$(cd "$(dirname "$0")/../.." && pwd)
w=${1:?usage: add-aux.sh WORKLOAD}
[[ $w =~ ^[a-zA-Z0-9_-]+$ ]] || exit 2
d=${FROZEN:-/home/exedev/targets/frozen}/$w
dest=${DATA_ROOT:-$here/data}/$w
out=$(mktemp -d)
trap 'rm -rf "$out"' EXIT
mapfile -t F < "$d/link.flags"
prlimit --as=8589934592 -- "$here/build/hlink" -nodetach -fresh -o "$out/a.out" \
  -importcfg "$d/importcfg.link" "${F[@]}" -s -w \
  -dumplive "$out/live.txt" -dumpflat "$out/flat" "$d/main.a"
mv "$out/live.txt" "$out/flat/oracle/live_names.txt"
# README is documentation copied by extract.sh, not generated by hlink.
cp "$dest/README.md" "$out/flat/README.md"
count=0
while IFS= read -r -d '' old; do
  rel=${old#"$dest/"}
  cmp "$old" "$out/flat/$rel"
  count=$((count + 1))
done < <(find "$dest" -type f -print0)
printf '%s %s: %d pre-existing files byte-identical\n' "$(date -u +%FT%TZ)" "$w" "$count"
for name in aux_start.u32 aux_pkg.u32 aux_idx.u32; do
  cp "$out/flat/$name" "$dest/$name"
done
